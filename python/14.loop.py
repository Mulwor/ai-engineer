# ================================================================
# ! Циклы в Python (for, while)
# ! Позволяют многократно выполнять блок кода.
# ================================================================
# ! ---------- 1. Цикл for по последовательности ----------
# ? Итерироваться можно по строкам, спискам, кортежам, словарям, 
# ? множествам, range() и т.д.

for item in ['a', 'b', 'c']:
    print(item)          # выведет a, b, c (каждый на новой строке)
for ch in "hello":
    print(ch)            # h, e, l, l, o
for num in (1, 2, 3):
    print(num ** 2)      # 1, 4, 9



# ! ---------- 2. range() – числовой диапазон ----------
# ? range(start, stop, step) – генерирует числа от start до stop-1
# ? с шагом step. Все параметры опциональны: range(stop) -> от 0 
# ? до stop-1.

for i in range(5):           # 0, 1, 2, 3, 4
    print(i)

for i in range(2, 6):        # 2, 3, 4, 5
    print(i)

for i in range(0, 10, 2):    # 0, 2, 4, 6, 8
    print(i)

for i in range(10, 0, -2):   # 10, 8, 6, 4, 2 (обратный шаг)
    print(i)



# ! ----- 3. Цикл while – выполняется, пока условие истинно -----
# ? Условие проверяется перед каждой итерацией.

x = 0
while x < 5:
    print(x)          # 0, 1, 2, 3, 4
    x += 1

# * Бесконечный цикл – с условием True, прерываем break.
# * while True:
# *    ответ = input("Введите 'exit' для выхода: ")
# *    if ответ == 'exit':
# *        break



# ! ---------- 4. Управление циклом: break и continue ----------
# ? break – полностью прерывает выполнение цикла.
# ? continue – переходит к следующей итерации (пропускает оставшуюся 
# ? часть тела).

for i in range(10):
    if i == 5:
        break          # выход при i == 5
    print(i)           # напечатает 0,1,2,3,4

for i in range(10):
    if i % 2 == 0:
        continue       # пропускаем чётные
    print(i)           # напечатает 1,3,5,7,9



# ! ---------- 5. Блок else для циклов ----------
# ? else выполняется, если цикл завершился НЕ через break.
# ? Если был break, else пропускается.

for i in range(3):
    print(i)
else:
    print("Цикл завершился без break")   # выполнится

for i in range(5):
    if i == 3:
        break
    print(i)
else:
    print("Не выполнится, так как был break")   # не выполнится

# То же для while:
x = 0
while x < 3:
    print(x)
    x += 1
else:
    print("while завершился без break")   # выполнится



# ! ---------- 6. Итерация по словарям ----------
d = {'a': 1, 'b': 2, 'c': 3}

# По умолчанию перебираются ключи
for key in d:
    print(key, d[key])

# Методы .keys(), .values(), .items()
for key in d.keys():
    print(key)

for val in d.values():
    print(val)

for key, val in d.items():
    print(f"{key} -> {val}")



# ! ---------- 7. enumerate() – получаем индекс и элемент ----------
# ? enumerate(sequence, start=0) возвращает пары (индекс, элемент)
lst = ['a', 'b', 'c']
for idx, val in enumerate(lst):
    print(idx, val)          # (0,'a'), (1,'b'), (2,'c')

for idx, val in enumerate(lst, start=1):   # начать с 1
    print(idx, val)          # (1,'a'), (2,'b'), (3,'c')



# ! ------ 8. zip() – параллельная итерация по нескольким последовательностям ----------
# ? zip объединяет элементы из нескольких итерируемых объектов в 
# ? кортежи до самой короткой последовательности.

names = ['Alice', 'Bob', 'Charlie']
scores = [85, 92, 78]
for name, score in zip(names, scores):
    print(f"{name}: {score}")

# ? Если последовательности разной длины, лишние отбрасываются.
# ? Для обработки всех элементов можно использовать 
# ? itertools.zip_longest.



# ! ---------- 9. Вложенные циклы ----------
# ? Цикл внутри цикла – полный перебор комбинаций.

for i in range(3):
    for j in range(2):
        print(f"({i}, {j})")   # (0,0), (0,1), (1,0), (1,1), (2,0), (2,1)



# ! --- 10. Генераторы списков (list comprehensions) – краткая форма циклов для создания списков ----
# ? [выражение for переменная in последовательность if условие]
# ? Это не цикл, но часто используется вместо for для создания списков.

squares = [x**2 for x in range(5)]            # [0, 1, 4, 9, 16]
even_squares = [x**2 for x in range(10) if x % 2 == 0]   # [0, 4, 16, 36, 64]

# Аналогично для множеств и словарей:
set_squares = {x**2 for x in range(5)}       # множество
dict_squares = {x: x**2 for x in range(5)}   # словарь {0:0, 1:1, 2:4, ...}

# Генераторные выражения (экономия памяти) – в круглых скобках:
gen = (x**2 for x in range(10))   # не вычисляется сразу, можно итерировать один раз.



# ! ---------- 11. Цикл for с break и else – пример поиска ----------
# ? Часто используется для поиска элемента с последующим действием.
items = [1, 2, 3, 4, 5]
target = 3
for item in items:
    if item == target:
        print("Нашли!")
        break
else:
    print("Не нашли")   # выполнится, только если break не сработал



# ! ---------- 12. Важные замечания и советы ----------
# - for по словарю перебирает ключи; для изменения словаря во время итерации – используйте копию.
# - Не изменяйте список во время итерации по нему – используйте срез или копию.
# - range() возвращает объект, который экономит память (не создаёт список).
# - В Python нет цикла do-while, но можно эмулировать через while True + break.
# - Для бесконечных циклов используйте while True.
# - Если нужно прервать внешний цикл из вложенного, можно использовать флаг или поместить логику в функцию и return.
# - Оператор pass используется как заглушка в пустых блоках.

# Пример безопасного удаления элементов из списка при итерации (итерация по копии):
lst = [1, 2, 3, 4]
for item in lst[:]:    # итерация по копии
    if item % 2 == 0:
        lst.remove(item)
print(lst)             # [1, 3]
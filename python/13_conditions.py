# =============================================================
# ! Условные конструкции в Python
# ! Управляют потоком выполнения в зависимости от истинности условий.
# =============================================================
# ! ---------- 1. Базовый синтаксис if/else ----------
# ? После условия ставится двоеточие, блок кода выделяется отступом (обычно 4 пробела).
x = 5
if x > 0:
    print("Число положительное")   # выполнится
else:
    print("Число не положительное")

# ? Можно записывать сравнения в цепочку (это эквивалентно and)
if 0 < x < 10:                     # True, так как 0 < 5 < 10
    print("x в диапазоне (0, 10)")



# ! ---------- 2. Операторы сравнения ----------
# ? ==, !=, >, <, >=, <=
# ? Сравнивать можно числа, строки, списки и другие типы (где это имеет смысл).
a, b = 10, 20
if a != b:
    print("a и b не равны")

# ? Сравнение списков — поэлементное
if [1, 2] == [1, 2]:
    print("Списки равны")



# ! ---------- 3. Логические операторы and, or, not ----------
# ? Приоритет: not > and > or. Для явного порядка используйте скобки.
# ? Короткое замыкание: второй операнд вычисляется только при необходимости.
a, b = 2, 3
if a == 2 and b == 3:
    print("Оба условия истинны")

if a > 0 or b < 0:
    print("Хотя бы одно истинно")

if not (a < 0):
    print("a не отрицательное")

# ? Пример короткого замыкания:
# ? if False and expensive_function():  # expensive_function не вызовется
# ?   pass



# ! ---------- 4. Оператор in (и not in) ----------
# ? Проверяет наличие элемента в последовательности (строке, списке, кортеже, множестве, ключах словаря).
lst = [1, 2, 3]
if 2 in lst:
    print("2 есть в списке")
if 4 not in lst:
    print("4 отсутствует")

# ? Для словарей in проверяет ключи, а не значения.
d = {'a': 1, 'b': 2}
if 'a' in d:
    print("Ключ 'a' есть")



# ! ---------- 5. Истинность и ложность объектов ----------
# ? В условном контексте любое значение приводится к bool.
# ? Ложными (False) считаются: None, 0, 0.0, пустые коллекции ("", [], (), {}, set(), range(0)).
# ? Всё остальное — True.
value = 5
if value:                 # эквивалентно if value != 0
    print("value истинно")

empty_list = []
if not empty_list:        # True, так как список пустой
    print("Список пуст")

# ! ---------- 6. Вложенные условия ----------
# ? Внутри блока if может быть ещё один if — это нормально, но старайтесь не злоупотреблять.
x = 10
if x > 0:
    if x % 2 == 0:
        print("Чётное положительное")
    else:
        print("Нечётное положительное")



# !---------- 7. Множественный выбор — elif ----------
# ? elif = else if. Проверяет условия последовательно до первого истинного.
score = 85
if score >= 90:
    grade = 'A'
elif score >= 80:
    grade = 'B'
elif score >= 70:
    grade = 'C'
else:
    grade = 'F'
print(grade)   # 'B'




# ! ---------- 8. Сопоставление с образцом — match/case (Python 3.10+) ----------
# ? Позволяет сравнивать значение с несколькими шаблонами.
# ? case _ — аналог default.
value = 'b'
match value:
    case 'a':
        print("Буква a")
    case 'b':
        print("Буква b")
    case _:
        print("Другая буква")

# Можно объединять варианты через |
match value:
    case 'a' | 'c':
        print("a или c")
    case 'b' | 'd':
        print("b или d")
    case _:
        print("Другое")



# ! ---------- 9. Тернарный оператор ----------
# ? Короткая запись для присваивания значения по условию.
# ? Синтаксис: значение_если_истина if условие else значение_если_ложь
a, b = 5, 10
result = "a больше" if a > b else "a не больше"
print(result)

# ? Можно использовать в выражениях, например, в print:
print("Чётное" if x % 2 == 0 else "Нечётное")



# ! ---------- 10. Проверка типа — isinstance() ----------
# ? Проверяет, принадлежит ли объект указанному типу (или кортежу типов).
x = "hello"
if isinstance(x, str):
    print("Это строка")
elif isinstance(x, int):
    print("Это целое число")

# ? Часто используемые типы: str, int, float, list, tuple, dict, set, bool.
# ? Можно проверять сразу несколько:
if isinstance(x, (int, float)):
    print("Числовой тип")



# ! ---------- 11. Пустой блок — pass ----------
# ! pass — инструкция-заглушка, ничего не делает. Нужна, когда блок должен быть пустым.
if condition:
    pass   # позже допишем логику
else:
    print("Выполняется else")



# ---------- 12. Важные замечания ----------
# - Условие не требует круглых скобок (хотя они допустимы).
# - После условия обязательно двоеточие.
# - Отступы определяют вложенность.
# - and и or работают по короткому замыканию.
# - Не злоупотребляйте глубокой вложенностью — используйте elif и логические операторы.
# - Для сравнения с None всегда используйте is None или is not None (не ==).
# =====================================================
# Базовые операторы сравнения (Comparison operators)
# =====================================================

# Равенство (Equal) и неравенство (Not equal)
print("1 == 1 =", 1 == 1)   # True
print("2 == 1 =", 2 == 1)   # False
print("1 != 1 =", 1 != 1)   # False
print("2 != 1 =", 2 != 1)   # True

# Сравнения больше/меньше
print("1 < 10 =", 1 < 10)   # True
print("1 > 10 =", 1 > 10)   # False
print("2 <= 2 =", 2 <= 2)   # True
print("2 >= 2 =", 2 >= 2)   # True


# =====================================================
# Цепочки сравнений (Chained comparisons)
# =====================================================

# ! Python позволяет записывать несколько сравнений в цепочку (как в математике)
# Это эквивалентно логическому И между всеми частями

print("1 < 2 and 2 < 3 =", 1 < 2 and 2 < 3)   # True
print("2 < 3 and 3 < 2 =", 2 < 3 and 3 < 2)   # False

# Цепочка проще и читаемее:
print("1 < 2 < 3 =", 1 < 2 < 3)     # True
print("2 < 3 < 2 =", 2 < 3 < 2)     # False

# Можно цепочки с разными операторами:
print("5 > 3 >= 3 =", 5 > 3 >= 3)   # True (5>3 и 3>=3)
print("5 == 5 <= 10 =", 5 == 5 <= 10)  # True


# =====================================================
# Сравнение разных типов (Type comparisons)
# =====================================================

# ! Числа (int, float) сравниваются по значению, типы не важны
print("3 == 3.0 =", 3 == 3.0)         # True
print("3 > 2.5 =", 3 > 2.5)           # True

# ! Сравнение int и str в Python 3 вызывает TypeError (ранее могло работать)
# print("3 == '3' =", 3 == '3')   # TypeError: '>' not supported между int и str

# Однако bool — подкласс int, поэтому сравнивается с числами:
print("True == 1 =", True == 1)       # True
print("False == 0 =", False == 0)     # True
print("True > 0 =", True > 0)         # True


# =====================================================
# Сравнение строк (String comparison)
# =====================================================

# ! Строки сравниваются лексикографически (по кодам Unicode)
print("'apple' < 'banana' =", 'apple' < 'banana')   # True (a < b)
print("'apple' > 'Apple' =", 'apple' > 'Apple')     # True (строчные буквы имеют больший код)
# ! В Python 3 все строки в Unicode, сравнение зависит от порядка символов

# Сравнение работает посимвольно, пока не найдётся различие:
print("'abc' < 'abcd' =", 'abc' < 'abcd')   # True (короткая строка меньше, если префикс совпадает)


# =====================================================
# Сравнение коллекций (списки, кортежи, словари)
# =====================================================

# ! Списки сравниваются поэлементно (лексикографически)
print("[1, 2] < [1, 3] =", [1, 2] < [1, 3])   # True (2 < 3)
print("[1, 2] == [1, 2] =", [1, 2] == [1, 2]) # True
print("[1, 2] > [1, 2, 0] =", [1, 2] > [1, 2, 0])  # True? Нет: [1,2] == [1,2] и затем сравнивается длина, но Python при равенстве элементов сравнивает длины
# На самом деле [1,2] > [1,2,0] → False, потому что при равенстве до конца первого, меньший список считается меньшим
print("[1, 2] > [1, 2, 0] =", [1, 2] > [1, 2, 0])   # False (потому что первый закончился, он меньше)

# ! Кортежи сравниваются аналогично
print("(1, 2) == (1, 2) =", (1, 2) == (1, 2))   # True

# ! Словари сравниваются по ключам и значениям (порядок не важен)
print("{'a':1} == {'a':1} =", {'a':1} == {'a':1})   # True
print("{'a':1} == {'b':2} =", {'a':1} == {'b':2})   # False
# ! Однако словари нельзя сравнивать на > или < (ошибка)
# print({'a':1} > {'b':2})  # TypeError


# =====================================================
# Операторы is и is not (сравнение по идентичности)
# =====================================================

# ! is проверяет, ссылаются ли переменные на один и тот же объект в памяти
# ! == проверяет равенство значений

a = [1, 2]
b = [1, 2]
c = a

print("a == b =", a == b)   # True (значения одинаковые)
print("a is b =", a is b)   # False (разные объекты)
print("a is c =", a is c)   # True (c ссылается на тот же объект)

# Для неизменяемых объектов (числа, строки) интерпретатор может кешировать:
x = 256
y = 256
print("x is y =", x is y)   # True (кеширование малых целых)
x = 257
y = 257
print("x is y =", x is y)   # False (может быть False, зависит от реализации)

# ! is — стандартный способ проверки на None (мы это уже обсуждали)
# None is None  # True


# =====================================================
# Операторы in и not in (проверка вхождения)
# =====================================================

# ! in проверяет, содержится ли значение в коллекции (списке, строке, словаре и т.д.)
print("'a' in 'apple' =", 'a' in 'apple')         # True
print("'b' in 'apple' =", 'b' in 'apple')         # False
print("2 in [1, 2, 3] =", 2 in [1, 2, 3])         # True
print("4 not in [1, 2, 3] =", 4 not in [1, 2, 3]) # True

# Для словарей проверяет наличие ключа:
d = {'name': 'John', 'age': 30}
print("'name' in d =", 'name' in d)   # True
print("'John' in d =", 'John' in d)   # False (ищет только ключи)


# =====================================================
# Особенности сравнения чисел с плавающей точкой
# =====================================================

# ! Из-за двоичного представления не все десятичные дроби точно представимы
print("0.1 + 0.2 == 0.3 =", 0.1 + 0.2 == 0.3)   # False (на самом деле 0.30000000000000004)

# Как правильно сравнивать числа с плавающей точкой — использовать tolerance:
epsilon = 1e-10
result = 0.1 + 0.2
expected = 0.3
print("abs(result - expected) < epsilon =", abs(result - expected) < epsilon)   # True

# Или использовать round:
print("round(0.1 + 0.2, 10) == round(0.3, 10) =", round(0.1 + 0.2, 10) == round(0.3, 10))   # True



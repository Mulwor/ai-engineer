# ============================================================
# ! Множества (set) в Python
# ! - изменяемый тип данных для хранения уникальных элементов.
# ! - элементы неупорядочены (не имеют индексов).
# ! - могут содержать только хешируемые (неизменяемые) типы: числа, строки, 
# ! кортежи (если все элементы хешируемы).
# ! - не могут содержать списки, словари или другие множества (но можно frozenset).
# ! - операции вставки, удаления, проверки наличия выполняются за O(1) в среднем.
# ============================================================

# ! ---------- 1. Создание множества ----------
st1 = set('abc')                # {'a', 'c', 'b'}  (порядок произвольный)
st2 = set(['1', '2', '3'])      # {'2', '3', '1'}
st3 = set((1, 1, 2, 3))         # {1, 2, 3}  (дубли удалены)
print(st1, st2, st3)
print(type(st1))                # <class 'set'>

# Пустое множество создаётся только через set(), {} — это словарь
empty_set = set()
empty_dict = {}

# ! ---------- 2. Длина ----------
print(len(st1))                 # 3



# ! ---------- 3. Доступ к элементам ----------
# ? Индексация отсутствует — доступ только через итерацию или проверку наличия.
# ? st1[0]  # TypeError: 'set' object is not subscriptable



# ! ---------- 4. Добавление элементов ----------
# ? .add(element) — добавляет один элемент
st1.add('e')                    # {'a', 'c', 'e', 'b'}

# ? .update(iterable) — добавляет все элементы из итерируемого объекта
st1.update('who')               # добавляет 'w','h','o' (строка итерируется по символам)
st1.update(['1','2','3'])       # добавляет строки '1','2','3'
st1.update((1, 2, 3))           # добавляет числа 1,2,3
st1.update({1: 'text1', 2: 'text2'})  # при передаче словаря добавляются только КЛЮЧИ (1, 2)

# ? Объединение двух множеств: st1.update(st2) или st1 |= st2
st1.update(st2)



# ! ---------- 5. Удаление элементов ----------
# ? .remove(element) — удаляет элемент, если его нет — KeyError
st1.remove('a')

# ? .discard(element) — удаляет элемент, если его нет — ничего не делает (возвращает None)
st1.discard('b')

# ? .pop() — удаляет и возвращает произвольный элемент (недетерминированный порядок)
print(st1.pop())   # случайный элемент
print(st1)

# ? .clear() — удаляет все элементы
st1.clear()



# ! ---------- 6. Проверка наличия ----------
st4 = {'a', 'b', 'c'}
print('a' in st4)          # True
print('e' not in st4)      # True



# ! ---------- 7. Подмножество: issubset (короткая форма <=) ----------
# ? Проверяет, все ли элементы текущего множества присутствуют 
# ? в другом итерируемом объекте.
st = {'1','2','3','4','5','6'}
txt = '123456'
print(st.issubset(txt))    # True (т.к. все строки '1'..'6' есть в строке)
st = {'ab','cd','ef'}
tlp = ('ab','cd','ef')
print(st.issubset(tlp))    # True
st1 = {1,2,3,4,5}
st2 = {1,2,3}
print(st1.issubset(st2))   # False
print(st1 <= st2)          # то же самое



# ? .issuperset (>=) — проверяет, является ли множество надмножеством
print(st1.issuperset(st2))   # True
print(st1 >= st2)



# ! ---------- 8. Равенство множеств (==) ----------
# ? Сравниваются элементы (порядок не важен)
print({1,2,3,4} == {2,1,3,4})   # True



# ! ---------- 9. Пересечение (intersection) — & ----------
a = {'a','b','c'}
b = {'x','w','c','a'}
print(a.intersection(b))   # {'c','a'}
print(a & b)               # {'c','a'}



# ! ---------- 10. Объединение (union) — | ----------
print(a.union(b))          # {'c','x','w','a','b'}
print(a | b)               # то же



# ! ---------- 11. Разность (difference) — - ----------
print(a.difference(b))     # {'b'}  (есть в a, нет в b)
print(b.difference(a))     # {'x','w'}
print(a - b)               # {'b'}
print(b - a)               # {'x','w'}



# ! ---------- 12. Симметрическая разность (symmetric_difference) — ^ ----------
# Элементы, которые есть только в одном из множеств
print(a.symmetric_difference(b))   # {'b','x','w'}
print(a ^ b)                       # {'b','x','w'}



# ! ---------- 13. Обновляющие операции (in-place) ----------
# ? .update()        — объединение ( |= )
# ? .intersection_update() — пересечение ( &= )
# ? .difference_update()   — разность ( -= )
# ? .symmetric_difference_update() — симметричная разность ( ^= )

c = {1,2,3}
c.intersection_update({2,3,4})   # c теперь {2,3}
c.difference_update({3})         # c теперь {2}
print(c)



# ! ---------- 14. Проверка на отсутствие пересечения (isdisjoint) ----------
print({1,2}.isdisjoint({3,4}))   # True
print({1,2}.isdisjoint({2,3}))   # False



# ! ---------- 15. Копирование ----------
# ? .copy() — поверхностная копия
new_set = st4.copy()



# ! ---------- 16. Преобразования ----------
lst = list(st4)          # ['a','b','c']  (порядок произвольный)
st_from_list = set(lst)  # обратно в множество



# ! ---------- 17. Неизменяемое множество (frozenset) ----------
# ? frozenset — неизменяемая версия set, может быть ключом словаря.
fs = frozenset([1,2,3])
print(fs)
# fs.add(4)  # AttributeError: 'frozenset' object has no attribute 'add'

d = {fs: "value"}   # можно использовать как ключ



# ! ---------- 18. Генераторы множеств (set comprehensions) ----------
squares = {x**2 for x in range(5)}          # {0,1,4,9,16}
even_squares = {x**2 for x in range(10) if x%2==0}



# ! ---------- 19. Важные замечания ----------
# ? - Множества не гарантируют порядок, но в Python 3.7+ они сохраняют 
# ? порядок вставки (но это деталь реализации, не стоит на это полагаться).
# ? - Операции над множествами очень быстрые (O(1) для добавления, удаления, проверки).
# ? - Нельзя добавлять изменяемые объекты (списки, словари), но можно 
# ? добавлять кортежи (если внутри хешируемые элементы).
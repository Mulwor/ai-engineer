# Кортеж - тип данных, похож на список, но его элементы нельзя
# добавлять, изменять или удалять (сам кортеж неизменяем).
# Используется для защиты данных от случайных изменений,
# занимает меньше памяти, чем списки такой же длины, и может
# быть ключом словаря (если все элементы хешируемы).

# ! ===== 1. Создание кортежа =====

# Классический способ с круглыми скобками
t1 = (1, 'str', True, False, ['a', 'b'])

# Без скобок (через запятую) — допустимо, но лучше использовать скобки для читаемости
t2 = 'a', 'b', 'c'

# С помощью функции tuple() из любого итерируемого объекта
t3 = tuple('abcde')        # ('a', 'b', 'c', 'd', 'e')
t4 = tuple([1, 2, 3])      # (1, 2, 3)
t5 = tuple(range(5))       # (0, 1, 2, 3, 4)

# Кортеж из одного элемента — обязательна запятая!
single = (42,)             # кортеж
not_tuple = (42)           # int (просто число)

mainExample = ('a', 'b', 'c')

# ! ===== 2. Доступ по индексу и срезы =====

t = (10, 20, 30, 40, 50)
print(t[0])      # 10
print(t[-1])     # 50
print(t[1:4])    # (20, 30, 40)  — срез
print(t[::-1])   # (50, 40, 30, 20, 10) — реверс через срез

# ! ===== 3. Неизменяемость =====

# Попытка изменить элемент — ошибка
# t[0] = 100   # TypeError: 'tuple' object does not support item assignment

calculate = (4, 6, 8, 10)
res = calculate[-1] + calculate[0]
# calculate[1] = res        # TypeError (раскомментируйте, чтобы увидеть)

# Важно: если внутри кортежа лежит изменяемый объект (например, список),
# то его содержимое менять можно, но сам элемент (ссылка) — нет.
t_inner = ([1, 2], 3)
t_inner[0].append(4)   # изменяем список внутри кортежа
print(t_inner)         # ([1, 2, 4], 3) — кортеж остался тем же, список изменился
# t_inner[0] = [5, 6]  # TypeError

# ! ===== 4. Длина =====

print(len(mainExample))   # 3

# ! ===== 5. Объединение и умножение =====

# Для демонстрации объединения определим переменные, которые были в вашем примере
cartage_01 = (1, 'str', True, False, ['a', 'b'])
cartage_02 = ('a', 'b', 'c')

print(cartage_01 + cartage_02)  # (1, 'str', True, False, ['a', 'b'], 'a', 'b', 'c')
print(mainExample * 2)          # ('a', 'b', 'c', 'a', 'b', 'c')

# ! ===== 6. Проверка вхождения (in / not in) =====

print('a' in mainExample)       # True (исправлено: True, а не true)
print('с' not in mainExample)   # True

# ! ===== 7. Методы кортежа =====

t_met = (1, 2, 2, 3, 2)
print(t_met.count(2))   # 3 — количество вхождений
print(t_met.index(3))   # 3 — индекс первого вхождения
print(t_met.index(2, 2)) # 2 — поиск с индекса 2

# ! ===== 8. Итерация =====

for item in mainExample:
    print(item, end=' ')   # a b c
print()

# ! ===== 9. Распаковка (unpacking) =====

txt1, txt2, txt3 = mainExample
print(txt1, txt2, txt3)         # 'a', 'b', 'c'

# Расширенная распаковка со звёздочкой
first, *middle, last = (1, 2, 3, 4, 5)
print(first, middle, last)      # 1 [2, 3, 4] 5

# ! ===== 10. Преобразования =====

# Преобразование в кортеж (из строки, списка и т.д.)
txt = 'abcde'
print(tuple(txt))               # ('a', 'b', 'c', 'd', 'e')

# Преобразование кортежа в список
print(list(mainExample))        # ['a', 'b', 'c']

# Слияние кортежа в строку (все элементы должны быть строками)
print('-'.join(mainExample))    # 'a-b-c'

# ! ===== 11. Кортеж как ключ словаря =====

d = {(1, 2): "point"}
print(d[(1, 2)])   # 'point'

# ! ===== 12. Вложенные кортежи =====

nested = ((1, 2), (3, 4))
print(nested[0][1])   # 2

# ! ===== 13. Именованные кортежи (дополнительно) =====

from collections import namedtuple
Point = namedtuple('Point', ['x', 'y'])
p = Point(10, 20)
print(p.x, p.y)   # 10 20


# =====================================================
# Срезы (slicing) в Python
# Синтаксис:  последовательность[начало:конец:шаг]
# - начало  — индекс первого включаемого элемента (по умолчанию 0)
# - конец   — индекс, до которого НЕ включаем (по умолчанию длина)
# - шаг     — шаг перебора (по умолчанию 1)
# Все параметры необязательны.
# Срез всегда создаёт НОВЫЙ объект (копию), не изменяя исходный.
# =====================================================



# ! ---------- 1. Базовые срезы (строки и списки) ----------
s = "abcde"
lst = ['a', 'b', 'c', 'd', 'e']

print(s[1:])    # 'bcde'   (с индекса 1 до конца)
print(s[:-1])   # 'abcd'   (с начала до предпоследнего)
print(s[1:3])   # 'bc'     (индексы 1 и 2, 3 не включён)
print(s[:3])    # 'abc'    (первые три)
print(s[3:])    # 'de'     (с третьего до конца)

print(lst[:4])    # ['a','b','c','d']
print(lst[2:-1])  # ['c','d']  (от индекса 2 до предпоследнего)



# ! ---------- 2. Отрицательные индексы ----------
# -1 — последний, -2 — предпоследний и т.д.
print(s[-1])      # 'e'
print(s[-3:])     # 'cde'  (последние три)
print(s[:-2])     # 'abc'  (все, кроме двух последних)



# ! ---------- 3. Шаг (третий параметр) ----------
nums = "123456789"

print(nums[0:10:2])   # '13579'  (индексы 0,2,4,6,8)
print(nums[1:9:2])    # '2468'   (индексы 1,3,5,7)   <-- исправлено!
print(nums[1:-1:2])   # '2468'   (то же самое)
print(nums[::2])      # '13579'  (все чётные индексы)
print(nums[1::2])     # '2468'   (все нечётные индексы)  <-- исправлено!
print(nums[:])        # '123456789' (полная копия)

print(lst[0:-1:3])    # ['a','d']  (индексы 0 и 3)



# ! ---------- 4. Отрицательный шаг (реверс) ----------
# При отрицательном шаге начало и конец интерпретируются в обратном порядке.
print(nums[::-1])     # '987654321' (полный реверс)
print(nums[7::-2])    # '8642'   (от индекса 7 вниз с шагом 2)
print(nums[-2::-2])   # '8642'   (то же самое, от предпоследнего)



# ! ---------- 5. Срезы для кортежей ----------
t = (1, 2, 3, 4, 5)
print(t[1:4])   # (2, 3, 4)  — работает, но кортеж неизменяем



# ! ---------- 6. Изменение списков через срез (присваивание) ----------
lst2 = [1, 2, 3, 4, 5]

# Замена части элементов
lst2[1:4] = [10, 20]      # заменили индексы 1,2,3 на два элемента
print(lst2)               # [1, 10, 20, 5]

# Вставка элементов (замена пустого среза)
lst2[1:1] = [99, 100]     # вставляем в позицию 1
print(lst2)               # [1, 99, 100, 10, 20, 5]

# Удаление через присваивание пустого списка
lst2[2:4] = []            # удалили элементы с индексами 2 и 3
print(lst2)               # [1, 99, 20, 5]

# Удаление через del (вы уже показали)
del lst2[1:3]             # удалили индексы 1 и 2
print(lst2)               # [1, 5]



# ! ---------- 7. Важное замечание: строки неизменяемы ----------
s2 = "hello"
# s2[1:3] = "xx"   # TypeError, так как строки нельзя изменять
del s2[1:3]        # тоже ошибка, строки не поддерживают удаление



# ! ---------- 8. Дополнительно: функция slice() ----------
# Создаёт объект среза, который можно переиспользовать
sl = slice(1, 5, 2)
print(nums[sl])   # '2468'  (тот же срез)
# =====================================================
# Словарь (dict) в Python
# Хранит данные в виде пар "ключ → значение".
# Ключи должны быть неизменяемыми (хешируемыми): числа, строки, кортежи (если все элементы хешируемы).
# Значения могут быть любыми объектами.
# Начиная с Python 3.7, словари сохраняют порядок вставки элементов.
# =====================================================

# ! ---------- 1. Создание словаря ----------
d1 = {'a': 1, 'b': 2, 'c': 3}                 # литерал
d2 = dict(a='1', b='2', e='4')                # через dict() (ключи без кавычек)
d3 = dict([('a', 1), ('b', 2)])               # из списка пар
d4 = {x: x**2 for x in range(3)}              # {0: 0, 1: 1, 2: 4} — словарное включение


# ! ---------- 2. Доступ и изменение ----------
print(d1['a'])          # 1 (если ключа нет — KeyError)
d1['a'] = '!'           # изменение существующего ключа
d1['x'] = '!'           # добавление новой пары
print(d1)               # {'a': '!', 'b': 2, 'c': 3, 'x': '!'}



# ! ---------- 3. Длина ----------
print(len(d1))          # 4




# ! ---------- 4 Объединение словарей (update) ----------
d1.update(d2)           # добавляет все пары из d2, при совпадении ключей — перезаписывает
print(d1)               # {'a': '1', 'b': '2', 'c': 3, 'x': '!', 'e': '4'}




# ! ---------- 5. Удаление элементов ----------
del d1['x']             # удаляет ключ, если нет — KeyError
print(d1)               # {'a': '1', 'b': '2', 'c': 3, 'e': '4'}




# ! ---------- 6. Извлечение с удалением: pop(key[, default]) ----------
# Возвращает значение и удаляет ключ. Если ключа нет — возвращает default (или KeyError)
print(d2.pop('a'))      # '1' (удалили 'a')
print(d2)               # {'b': '2', 'e': '4'}
print(d2.pop('н', '!')) # '!'  (ключа нет, вернули значение по умолчанию)  <-- исправлено!




# ! ---------- 7. Извлечение последней пары: popitem() ----------
# Возвращает и удаляет последнюю добавленную пару (кортеж (ключ, значение))
print(d2.popitem())     # ('e', '4')  (зависит от порядка вставки)
print(d2)               # {'b': '2'}




# ! ---------- 8. Очистка: clear() ----------
d2.clear()              # очищает словарь
print(d2)               # {}
print(d2.clear())       # None (метод ничего не возвращает)  <-- исправлено!




# ! ---------- 9. Проверка наличия ключа ----------
print('a' in d1)        # True
print('c' not in d1)    # False




# ! ---------- 10. Безопасное получение: get(key[, default]) ----------
print(d1.get('a'))          # '1'
print(d1.get('z', 42))      # 42 (ключа нет, вернули 42)
print(d1.get('z'))          # None (без второго параметра)




# ! ---------- 11. Установка значения по умолчанию: setdefault(key[, default]) ----------
# Если ключ есть — возвращает его значение, иначе вставляет ключ со значением default и возвращает его.
d = {'x': 10}
print(d.setdefault('y', 20))   # 20 (ключ 'y' добавлен)
print(d)                        # {'x': 10, 'y': 20}
print(d.setdefault('x', 99))    # 10 (ключ есть, значение не меняется)




# ! ---------- 12. Получение всех ключей, значений, пар ----------
keys = d1.keys()          # dict_keys(['a', 'b', 'c', 'e'])
values = d1.values()      # dict_values(['1', '2', 3, '4'])
items = d1.items()        # dict_items([('a', '1'), ('b', '2'), ('c', 3), ('e', '4')])

print(list(keys))         # ['a', 'b', 'c', 'e']
print(list(values))       # ['1', '2', 3, '4']
print(list(items))        # [('a', '1'), ('b', '2'), ('c', 3), ('e', '4')]




# ! ---------- 13. Итерация по словарю ----------
for key in d1:            # по умолчанию перебирает ключи
    print(key, d1[key])
for key, val in d1.items():
    print(key, val)



# ! ---------- 14. Преобразования ----------
# Из словаря в список ключей, значений или пар (уже показано выше)

# В словарь можно преобразовать:
# - список кортежей (или список списков) вида [(key, value), ...]
# - список строк? Нет, но можно передать итератор из пар.
lst_pairs = [['a', '1'], ['b', '2']]
tuple_pairs = ((1, 'a'), (2, 'b'))
print(dict(lst_pairs))    # {'a': '1', 'b': '2'}
print(dict(tuple_pairs))  # {1: 'a', 2: 'b'}

# Нельзя передать строку или число напрямую — они не являются итераторами пар.
# dict('abc') -> ошибка, потому что строка даёт символы, а не пары.



# ! ---------- 15. Вложенные словари ----------
nested = {
    'user1': {'name': 'Alice', 'age': 30},
    'user2': {'name': 'Bob', 'age': 25}
}
print(nested['user1']['name'])  # 'Alice'



# ! ---------- 16. Копирование ----------
original = {'a': [1, 2], 'b': 3}
copy_shallow = original.copy()        # поверхностная копия (вложенные объекты общие)
import copy
copy_deep = copy.deepcopy(original)   # полная копия (все уровни)



# ! ---------- 17. Словарные включения (dict comprehensions) ----------
squares = {x: x**2 for x in range(5)}   # {0: 0, 1: 1, 2: 4, 3: 9, 4: 16}
even_squares = {x: x**2 for x in range(10) if x % 2 == 0}



# ! ---------- 18. Использование неизменяемых ключей ----------
# Ключами могут быть строки, числа, кортежи (если внутри только хешируемые элементы)
d = {(1, 2): "point", 42: "answer", "key": "value"}
# d[[1,2]] = "list"  # TypeError, список изменяем — нельзя.




# ! ---------- 19. Удаление ключей без ошибки (pop с умолчанием) ----------
# Удаляем, если ключ есть, иначе ничего не делаем
d.pop('несуществующий', None)





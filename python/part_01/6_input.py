# Запрашиваем два числа и складываем их
num1 = input("Введите первое число: ")
num2 = input("Введите второе число: ")
# Преобразуем строки в числа с плавающей точкой (для поддержки дробей)
summa = float(num1) + float(num2)
print(f"Сумма: {num1} + {num2} = {summa}")

# Или сразу с преобразованием:
a = float(input("Введите a: "))
b = float(input("Введите b: "))
print(f"a + b = {a + b}")
print(f"a * b = {a * b}")
# =====================================================
# ! Переменные (Variables) — это имя, которое ссылается на объект в памяти
# ! Присваивание происходит через знак '='
# =====================================================
# ? Создаём и обновляем переменную
test = 1
print("test =", test)   # 1

test = 2                # переменная может менять значение
print("test =", test)   # 2

check = test + 3        # можно использовать в выражениях
print("check =", check) # 5


# =====================================================
# ! Правила именования переменных
# =====================================================

# ? Имя переменной должно начинаться с буквы (a-z, A-Z) или подчёркивания '_'
# ? Остальные символы: буквы, цифры, подчёркивания
# ? Имена чувствительны к регистру (myVar и myvar — разные)

valid_name = 10
_private = "скрыто"
myVar = 20
MY_CONST = 3.14

# ? Некорректные имена (закомментированы, чтобы не вызывать ошибку):
# 1var = 5          # нельзя начинать с цифры
# my-var = 5        # дефис не разрешён
# class = 5         # нельзя использовать зарезервированные слова (class, if, for, etc.)

# ? Рекомендации (PEP 8): имена переменных пишем строчными буквами, слова через подчёркивание
user_age = 25
first_name = "John"
total_sum = 100

# ? Для констант — все заглавные с подчёркиваниями:
MAX_SIZE = 1024
PI = 3.14159


# =====================================================
# ! Динамическая типизация (переменная может менять тип)
# =====================================================
# ! Python — язык с динамической типизацией: переменная не привязана к типу
# ! Она может ссылаться на объект любого типа в любой момент

var = 10
print("var =", var, "тип:", type(var))   # int

var = "Hello"
print("var =", var, "тип:", type(var))   # str

var = 3.14
print("var =", var, "тип:", type(var))   # float

var = [1, 2, 3]
print("var =", var, "тип:", type(var))   # list


# =====================================================
# ! Множественное присваивание
# =====================================================

# ! Можно присвоить значение нескольким переменным одновременно
a = b = c = 0
print("a =", a, "b =", b, "c =", c)   # все равны 0

# ! Можно обменять значения без временной переменной
x = 5
y = 10
print("До обмена: x =", x, "y =", y)
x, y = y, x
print("После обмена: x =", x, "y =", y)   # 10 5

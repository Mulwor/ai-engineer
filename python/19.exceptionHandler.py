# =============================================================
# ! Обработка исключений (Exception Handling) в Python
# ! Позволяет управлять ошибками и исключительными ситуациями,
# ! предотвращая аварийное завершение программы.
# =============================================================

# ! ---------- 1. Базовый синтаксис try/except ----------
# ? Код, который может вызвать ошибку, помещается в блок try.
# ? Если ошибка возникает, выполнение переходит в блок except.
# ? Если ошибки нет, except пропускается.
try:
    x = int(input("Введите число: "))
    print(f"Вы ввели {x}")
except:
    print("Произошла ошибка ввода!")

# ! ВАЖНО: Перехватывать все исключения "голым" except не рекомендуется,
# ! так как это может скрыть неожиданные ошибки (например, KeyboardInterrupt).
# ! Лучше указывать конкретные типы исключений.


# ! ---------- 2. Перехват конкретных исключений ----------
# ? Указываем класс исключения (или несколько через кортеж).
# ? Тогда except сработает только для указанных типов.
try:
    number = int(input("Число: "))
    result = 10 / number
    print(f"Результат: {result}")
except ValueError:
    print("Ошибка: введено не число!")
except ZeroDivisionError:
    print("Ошибка: деление на ноль!")

# ? Можно перехватывать несколько типов в одном except, передав кортеж:
try:
    # какой-то опасный код
    pass
except (ValueError, ZeroDivisionError):
    print("Ошибка значения или деление на ноль")




# ! ---------- 3. Доступ к объекту исключения ----------
# ? Используем as <переменная>, чтобы получить доступ к экземпляру исключения.
try:
    x = int(input("Число: "))
except ValueError as e:
    print(f"Ошибка: {e}")          # Выведет сообщение об ошибке
    print(f"Тип: {type(e).__name__}")




# ! ---------- 4. Блок else ----------
# ? else выполняется, если блок try завершился без исключений.
# ? Полезно для кода, который должен выполняться только при успешной работе try.
try:
    file = open("data.txt", "r")
    content = file.read()
except FileNotFoundError:
    print("Файл не найден")
else:
    print("Файл успешно прочитан")
    print(content[:100])   # покажем первые 100 символов
    file.close()
# ? else позволяет отделить "успешный" код от кода обработки ошибок.


# ! ---------- 5. Блок finally ----------
# ? finally выполняется всегда, независимо от того, было исключение или нет.
# ? Часто используется для освобождения ресурсов (закрытие файлов, соединений).
try:
    f = open("log.txt", "a")
    f.write("Запись в лог\n")
except Exception as e:
    print(f"Ошибка записи: {e}")
finally:
    f.close()   # файл будет закрыт в любом случае
    print("Файл закрыт")

# ? finally может быть использован без except, только с try и finally.
# ? В таком случае исключение не перехватывается, но finally выполнится перед выходом.



# ! ---------- 6. Генерация исключений (raise) ----------
# ? Используем raise, чтобы вызвать исключение вручную.
# ? Можно указать свой тип и сообщение.
def check_age(age):
    if age < 0:
        raise ValueError("Возраст не может быть отрицательным")
    if age < 18:
        raise ValueError("Доступ запрещён: возраст меньше 18")
    return "Доступ разрешён"

try:
    print(check_age(-5))
except ValueError as e:
    print(f"Ошибка: {e}")



# ? Перебрасывание исключения (без аргументов) — используется в except,
# ? чтобы обработать частично, а затем передать дальше.
try:
    risky_call()
except SomeError:
    log_error()
    raise   # пробрасываем то же исключение дальше



# ! ---------- 7. Собственные исключения (наследование от Exception) ----------
# ? Создайте класс, наследующий от Exception (или его подклассов).
# ? Можно добавлять атрибуты для передачи дополнительной информации.
class NegativeNumberError(Exception):
    """Исключение для отрицательных чисел"""
    pass

class InvalidInputError(Exception):
    def __init__(self, message, input_value):
        super().__init__(message)
        self.input_value = input_value

def process_number(n):
    if n < 0:
        raise NegativeNumberError("Число не должно быть отрицательным")
    if n == 0:
        raise InvalidInputError("Ноль недопустим", n)
    return 100 / n

try:
    process_number(-5)
except NegativeNumberError as e:
    print(f"Ошибка: {e}")
except InvalidInputError as e:
    print(f"Ошибка: {e}, введено: {e.input_value}")




# ! ---------- 8. Конструкция try-except-else-finally вместе ----------
# ? Порядок: try -> except -> else -> finally (finally всегда в конце).
try:
    data = {"key": "value"}
    print(data["key"])
except KeyError:
    print("Ключ не найден")
else:
    print("Ключ найден, всё хорошо")
finally:
    print("Это выполнится всегда")


# ! ---------- 9. Вложенные блоки try ----------
# ? Можно использовать try внутри try.
# ? Внутренний блок обрабатывает свои ошибки, внешний — свои.
try:
    file = open("config.txt")
    try:
        content = file.read()
        number = int(content)
    except ValueError:
        print("Ошибка преобразования в число")
    finally:
        file.close()
except FileNotFoundError:
    print("Файл config.txt не найден")



# ! ---------- 10. Контекстный менеджер with (не совсем try/except, но тесно связан) ----------
# ? with автоматически управляет ресурсами (вызывает __enter__ и __exit__).
# ? При возникновении исключения внутри блока, __exit__ вызывается с информацией об исключении.
# ? Это удобно для файлов, соединений с БД и т.п.
with open("file.txt", "r") as f:
    data = f.read()
# ? Файл будет закрыт автоматически, даже если возникнет исключение.

# ? Можно использовать with для собственных контекстных менеджеров (через contextlib или __enter__/__exit__).



# ! ---------- 11. Утверждения (assert) как средство отладки ----------
# ? assert проверяет условие и бросает AssertionError, если оно ложно.
# ? Используется для отладки, но не для обработки ошибок в продакшене
# ? (может быть отключено при запуске с флагом -O).
x = 10
assert x > 0, "x должен быть положительным"  # ОК
# assert x < 0, "x должен быть отрицательным"  # AssertionError



# ! ---------- 12. Иерархия исключений ----------
# ? Все исключения наследуются от BaseException.
# ? Основные: Exception (для всех обычных ошибок), SystemExit, KeyboardInterrupt.
# ? Перехватывать BaseException или Exception без разбора — рискованно.
# ? Лучше перехватывать конкретные подклассы Exception.

# ? Самые распространённые встроенные исключения:
#   - ValueError, TypeError, NameError, IndexError, KeyError, FileNotFoundError, ZeroDivisionError, AttributeError, ImportError, и др.



# ! ---------- 13. Правила и рекомендации ----------
# - Не используйте голый except: перехватывайте конкретные типы.
# - Не игнорируйте исключения молча (пустой except) — хотя бы логируйте.
# - Используйте finally для освобождения ресурсов, либо конструкцию with.
# - Создавайте свои исключения для специфических ошибок вашего приложения.
# - Исключения — не инструмент управления потоком, а для обработки ошибок.
# - При перехвате нескольких исключений, порядок except важен: дочерние классы должны идти раньше родительских.
#   (например, сначала ValueError, потом Exception).
# - raise без аргументов в except — перебрасывает текущее исключение.
# - Используйте else, чтобы отделить успешный код от защищаемого.
# - Не используйте assert для проверки пользовательского ввода — используйте raise с соответствующим исключением.

# Пример правильной структуры:
try:
    # код, который может вызвать ошибку
    pass
except (ValueError, ZeroDivisionError) as e:
    # обработка известных ошибок
    print(f"Ошибка: {e}")
except Exception as e:
    # обработка всех остальных исключений (с логированием)
    print(f"Неожиданная ошибка: {e}")
    raise   # пробросить дальше, если не можем обработать
else:
    # код, если ошибок не было
    pass
finally:
    # код, который выполняется всегда
    pass
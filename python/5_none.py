# =====================================================
# ! Специальное значение None (ничего)
# =====================================================

# ! None — это объект-синглтон, который обозначает "отсутствие значения"
# ! Используется, когда нужно показать, что переменная или результат ничего не содержат

test = None
print("test =", test)   # выведет None

# None не является строкой, числом, списком и т.д.
print("Тип None:", type(None))   # <class 'NoneType'>



# =====================================================
# ! Проверка на None: используйте is, НЕ ==
# =====================================================

# ! Оператор is проверяет идентичность объектов (один и тот же объект в памяти)
# ! == проверяет равенство значений (может быть переопределено)
# ! None — синглтон, поэтому проверка через is является правильной и быстрой

print("'etc' is None =", "etc" is None)   # False
print("None is None =", None is None)     # True

# ! Сравнение через == тоже работает, но не рекомендуется (может привести к ошибкам)
print("'etc' == None =", "etc" == None)   # False
print("None == None =", None == None)     # True

# ! Почему is лучше? Потому что объект None единственный, и is проверяет именно его.
# ! Некоторые классы могут переопределить __eq__, и тогда == может дать неожиданный результат.



# =====================================================
# ! Где используется None?
# =====================================================

# * 1. Возвращаемое значение функций, которые явно ничего не возвращают
def do_nothing():
    pass

result = do_nothing()
print("Функция без return возвращает:", result)   # None

# * 2. Значение по умолчанию для аргументов (особенно для изменяемых типов)
def greet(name=None):
    if name is None:
        name = "Гость"
    print(f"Привет, {name}!")

greet()           # Привет, Гость!
greet("Анна")     # Привет, Анна!

# * 3. Обозначение отсутствующего значения в структурах данных
my_dict = {"key": None}
print("my_dict['key'] =", my_dict["key"])   # None

# * 4. Инициализация переменных, которые будут заполнены позже
user = None
# * ... какой-то код, который может присвоить значение
user = "Петя" if some_condition else None



# =====================================================
# ! Проверка существования переменной через None
# =====================================================

data = None
if data is None:
    print("Данные отсутствуют")
else:
    print("Данные:", data)

# ? Часто используют в связке с or для подстановки значения по умолчанию
value = None
result = value or "default"   # если value None (или любой falsy), то "default"
print("result =", result)     # "default"

# ! Но будьте внимательны: если value может быть пустой строкой или 0, они тоже falsy,
# ! и or подставит default. Иногда это нежелательно.



# =====================================================
# ! Отличия None от других falsy значений
# =====================================================
# * None — отдельный тип, не равен 0, пустой строке, пустому списку и т.д.
print("None == 0 =", None == 0)         # False
print("None == '' =", None == "")       # False
print("None == [] =", None == [])       # False
print("None == False =", None == False) # False

# Но bool(None) тоже False:
print("bool(None) =", bool(None))       # False



# =====================================================
# ! Важно: никогда не сравнивайте с None через == в условных конструкциях
# =====================================================
# ? Плохо (хотя и работает):
if result == None:   # так не делайте
    print("Нет результата")

# ? Хорошо:
if result is None:
    print("Нет результата")

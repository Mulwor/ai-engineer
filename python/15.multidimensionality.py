# ! ---------- 7. Полезные операции с матрицами ----------
# ? Транспонирование матрицы (перестановка строк и столбцов)
matrix = [[1, 2, 3], [4, 5, 6], [7, 8, 9]]
transposed = [[row[i] for row in matrix] for i in range(len(matrix[0]))]
print(transposed)  # [[1,4,7], [2,5,8], [3,6,9]]

# ? Транспонирование с помощью zip (элегантный способ)
transposed_zip = list(zip(*matrix))   # возвращает кортежи, можно обернуть в list
print(transposed_zip)

# ? Сумма всех элементов
total = sum(sum(row) for row in matrix)

# ? Поиск максимума и его индексов
max_val = matrix[0][0]
max_pos = (0, 0)
for i, row in enumerate(matrix):
    for j, val in enumerate(row):
        if val > max_val:
            max_val = val
            max_pos = (i, j)
print(f"Максимум {max_val} на позиции {max_pos}")



# ! ---------- 8. Копирование многомерных списков ----------
# ? Поверхностная копия (копируется только внешний список)
shallow_copy = matrix.copy()         # или matrix[:]
# ? Изменение вложенного списка отразится в обеих ссылках
# ? Глубокая копия (рекурсивно копирует все уровни)
import copy

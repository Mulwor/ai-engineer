# ? Создание матрицы заданного размера с помощью генератора списков
rows, cols = 3, 4
matrix_zeros = [[0] * cols for _ in range(rows)]   # правильный способ
# ? Внимание: [[0] * cols] * rows создаст ссылки на один и тот же вложенный список!

# ?  Создание матрицы с заполнением по формуле
matrix_identity = [[1 if i == j else 0 for j in range(3)] for i in range(3)]
# [[1,0,0], [0,1,0], [0,0,1]]



# ! ---------- 2. Доступ к элементам по индексам ----------
# ? Обращение к элементу: имя_списка[строка][столбец]
print(matrix[0][1])        # ? 2 (первая строка, второй столбец)
print(matrix[2][2])        # ? 9

# ? Изменение элемента
matrix[1][2] = 100
print(matrix)              # вторая строка теперь [4, 5, 100]

# ? Отрицательные индексы тоже работают
print(matrix[-1][-1])      # последний элемент последней строки (9)



# ! ---------- 3. Срезы для многомерных списков ----------
# ? Срез работает только для внешнего уровня, возвращая список строк.
sub_matrix = matrix[1:3]   # ? строки с индексом 1 и 2 (все столбцы)
print(sub_matrix)          # ? [[4,5,100], [7,8,9]]

# ? Чтобы получить подматрицу (строки и столбцы) – нужны
# ? дополнительные шаги. Например, получить все элементы из 
# ? строк 0-1 и столбцов 1-2:
sub = [row[1:3] for row in matrix[:2]]   # результат – список строк с обрезанными столбцами
print(sub)                 # [[2,3], [5,100]]



# ! ---------- 4. Обход многомерного списка (вложенные циклы) ----------
# ? Простой обход всех элементов:
for row in matrix:
    for elem in row:
        print(elem, end=' ')
    print()   # перевод строки после каждой строки

# Доступ по индексам строк и столбцов:
for i in range(len(matrix)):
    for j in range(len(matrix[i])):
        print(matrix[i][j], end=' ')
    print()

# Использование enumerate для получения индексов:
for i, row in enumerate(matrix):
    for j, val in enumerate(row):
        print(f"matrix[{i}][{j}] = {val}")



# ! ---------- 5. Изменение размера многомерного списка ----------
# ? Добавление новой строки (списка)
matrix.append([10, 11, 12])

# ? Добавление нового столбца (т.е. добавление элемента в каждую строку)
for row in matrix:
    row.append(0)   # теперь все строки имеют 4 элемента

# ? Удаление строки
del matrix[2]        # удаляем третью строку

# ? Удаление столбца (удаляем элемент из каждой строки)
for row in matrix:
    del row[1]       # удаляем второй столбец во всех строках



# ! ---------- 6. Генераторы многомерных списков ----------
# ? Создание таблицы умножения 10x10

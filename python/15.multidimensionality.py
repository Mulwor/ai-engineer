# ! ---------- 11. Практический пример: игра "Крестики-нолики" (доска 3x3) ----------
board = [[' ' for _ in range(3)] for _ in range(3)]

def print_board(b):
    for row in b:
        print('|'.join(row))
        print('-' * 5)

print_board(board)

# Ход игрока
board[1][1] = 'X'
board[0][2] = 'O'
print_board(board)


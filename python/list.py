# =====================================================
# ! Списки (Lists) — упорядоченные изменяемые коллекции
# =====================================================
# ! Список — это упорядоченная коллекция элементов, которые могут быть разных типов
# ! Элементы разделяются запятыми, список заключается в квадратные скобки []

test_01 = [1, 'str', True, False, ['a', 'b']]
print("Элемент по индексу 0:", test_01[0])              # 1
print("Сложение элементов:", test_01[0] + test_01[2])   # 1 + 1 => 2 (True == 1)
print("Отрицательный индекс:", test_01[-1])             # ['a', 'b'] (последний элемент)
print("Длина списка:", len(test_01))                    # 5


# =====================================================
# ! Создание списков разными способами
# =====================================================

# ! 1. Квадратные скобки
empty = []
numbers = [1, 2, 3]

# ! 2. Функция list() — преобразует итерируемый объект в список
print("list('1234'):", list('1234'))    # ['1', '2', '3', '4'] — каждый символ становится элементом
print("list('abcde'):", list('abcde'))  # ['a', 'b', 'c', 'd', 'e']
# list(5678)  # Ошибка! int не является итерируемым

# ! 3. Метод split() у строк — разбивает строку по разделителю
text = '1-2-3-4'
print("split('-'):", text.split('-'))   # ['1', '2', '3', '4']
print("split() без аргумента:", text.split())  # ['1-2-3-4'] (разбивает по пробелам)



# =====================================================
# ! Изменение элементов по индексу
# =====================================================
# ! Списки изменяемы (mutable) — можно менять элементы по индексу
lst = [1, 2, 3]
lst[0] = '!'   # замена первого элемента
print("После замены lst[0]:", lst)   # ['!', 2, 3]



# =====================================================
# ! Основные методы добавления элементов
# =====================================================

lst = ['a', 'b', 'c']

# ! append(element) — добавляет элемент в конец списка (изменяет исходный)
lst.append('d')
print("append('d'):", lst)   # ['a', 'b', 'c', 'd']

# ! insert(index, element) — вставляет элемент на позицию index, сдвигая остальные вправо
lst.insert(1, '2')
print("insert(1, '2'):", lst)   # ['a', '2', 'b', 'c', 'd']

# ! extend(iterable) — добавляет все элементы из итерируемого объекта в конец
lst2 = [4, 5, 6]
lst.extend(lst2)
print("extend([4,5,6]):", lst)   # ['a', '2', 'b', 'c', 'd', 4, 5, 6]

# Важно: append vs extend
# append добавляет объект целиком как один элемент
lst3 = [1, 2]
lst3.append([3, 4])
print("append([3,4]):", lst3)   # [1, 2, [3, 4]] — вложенный список

lst4 = [1, 2]
lst4.extend([3, 4])
print("extend([3,4]):", lst4)   # [1, 2, 3, 4] — элементы добавились по отдельности

# ! Сложение списков (+) создаёт новый список, а += изменяет исходный
lst5 = [1, 2]
lst6 = [3, 4]
res = lst5 + lst6   # создаётся новый список
print("lst5 + lst6 =", res)     # [1, 2, 3, 4]
print("lst5 остался:", lst5)    # [1, 2] (не изменился)

lst5 += lst6   # изменяет lst5
print("lst5 += lst6:", lst5)    # [1, 2, 3, 4]


# =====================================================
# ! Удаление элементов из списка
# =====================================================

lst = [1, 2, 3, 2]

# ! del — удаляет элемент по индексу или срез
del lst[0]
print("del lst[0]:", lst)   # [2, 3, 2]

# ! remove(element) — удаляет ПЕРВОЕ вхождение элемента по значению
lst.remove(2)   # удаляет первый встреченный 2
print("remove(2):", lst)    # [3, 2] (первая двойка удалена)

# ! pop(index) — удаляет элемент по индексу и ВОЗВРАЩАЕТ его
lst = [1, 2, 3]
popped = lst.pop(0)
print("pop(0):", popped)    # 1
print("список после pop:", lst)   # [2, 3]

# pop() без аргумента удаляет последний элемент
last = lst.pop()
print("pop() без индекса:", last)   # 3
print("список:", lst)   # [2]

# ! clear() — удаляет все элементы
lst = [1, 2, 3]
lst.clear()
print("clear():", lst)   # []


# =====================================================
# ! Поиск и проверка вхождения
# =====================================================

lst = [1, 2, 3, 2]

# ! index(element) — возвращает индекс ПЕРВОГО вхождения
print("index(2):", lst.index(2))   # 1 (индекс первой двойки)
# Если элемента нет — возникает ValueError
# print(lst.index(5))  # ValueError

# ! in — проверяет наличие элемента в списке
print("1 in lst:", 1 in lst)   # True
print("5 in lst:", 5 in lst)   # False

# ! count(element) — считает количество вхождений
print("count(2):", lst.count(2))   # 2


# =====================================================
# ! Сортировка и изменение порядка
# =====================================================

lst = [3, 1, 4, 2]

# ! sort() — сортирует список ПО МЕСТУ (изменяет исходный)
lst.sort()
print("sort():", lst)   # [1, 2, 3, 4]

# ! sort(reverse=True) — сортировка по убыванию
lst.sort(reverse=True)
print("sort(reverse=True):", lst)   # [4, 3, 2, 1]

# ! sorted(list) — возвращает НОВЫЙ отсортированный список, исходный не меняется
original = [3, 1, 4, 2]
new_sorted = sorted(original)
print("sorted(original):", new_sorted)   # [1, 2, 3, 4]
print("original остался:", original)      # [3, 1, 4, 2]

# ! reverse() — меняет порядок элементов на обратный (по месту)
lst = [1, 2, 3]
lst.reverse()
print("reverse():", lst)   # [3, 2, 1]


# =====================================================
# ! Преобразование списка в строку (join)
# =====================================================

# ! join() — метод строки, объединяет элементы списка в строку через разделитель
words = ['Hello', 'world', '!']
result = ' '.join(words)   # разделитель — пробел
print("join():", result)   # "Hello world !"

# Важно: все элементы списка должны быть строками, иначе ошибка
# numbers = [1, 2, 3]
# print(' - '.join(numbers))  # TypeError


# =====================================================
# ! Дополнительные полезные приёмы
# =====================================================

# ! Срезы (slicing) — получение подсписка
lst = [0, 1, 2, 3, 4, 5]
print("lst[1:4]:", lst[1:4])   # [1, 2, 3] (с 1-го по 3-й включительно)
print("lst[:3]:", lst[:3])     # [0, 1, 2] (первые три)
print("lst[::2]:", lst[::2])   # [0, 2, 4] (каждый второй)

# ! Копирование списка (важно, чтобы не изменять исходный)
# Простое присваивание копирует ссылку
a = [1, 2, 3]
b = a
b.append(4)
print("a после изменения b:", a)   # [1, 2, 3, 4] — изменился!

# Правильные способы копирования:
c = a.copy()          # метод copy()
d = a[:]              # срез от начала до конца
e = list(a)           # конструктор list()
# Теперь изменение копий не затронет оригинал

# ! max(), min(), sum() — работают со списками чисел
numbers = [10, 20, 5, 30]
print("max:", max(numbers))   # 30
print("min:", min(numbers))   # 5
print("sum:", sum(numbers))   # 65



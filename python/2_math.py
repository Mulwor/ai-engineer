# ! 4. Приоритет операций (Operator precedence)
# =====================================================
# ? Скобки явно задают порядок вычислений, как в математике
result = 4 - 1 + (5 + 6 * (2 + 7))   # сначала (2+7)=9, затем 6*9=54, потом 5+54=59, далее 4-1+59=62
print("Приоритет операций (со скобками):", result)   # 62

# ? Без скобок приоритет стандартный: сначала **, потом *, /, //, %, затем +, -
result2 = 4 - 1 + 5 + 6 * 2 + 7      # 6*2=12, затем 4-1+5+12+7 = 27
print("Без скобок (стандартный приоритет):", result2)



# =====================================================
# ! 5. Полезные замечания (Useful notes)
# =====================================================
# - Деление '/' всегда возвращает float, даже если результат целый (4/2 -> 2.0)
# - Целочисленное деление '//' округляет вниз (для отрицательных чисел тоже!)
print("10 // 3 =", 10 // 3)    # 3
print("-10 // 3 =", -10 // 3)  # -4 (а не -3!)
# - Остаток '%' сохраняет знак делителя
print("10 % 3 =", 10 % 3)      # 1
print("-10 % 3 =", -10 % 3)    # 2 (так как -10 = (-4)*3 + 2)

# - Возведение в степень '**' работает и с float, и с большими целыми
print("2 ** 10 =", 2 ** 10)    # 1024
print("2 ** 0.5 =", 2 ** 0.5)  # 1.4142135623730951 (квадратный корень)